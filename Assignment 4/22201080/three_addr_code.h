#ifndef THREE_ADDR_CODE_H
#define THREE_ADDR_CODE_H

#include <cstdio>
#include <string>
#include <vector>
using namespace std;

// -------------------------------------------------------------------------
// Generates fresh temporary variable names (t0, t1, t2, ...) and
// fresh label names (L0, L1, L2, ...) for the three address code.
// -------------------------------------------------------------------------
class TempVarManager {
    int counter;
public:
    TempVarManager() : counter(0) {}
    string new_temp() { return "t" + std::to_string(counter++); }
    void reset() { counter = 0; }
};

class LabelManager {
    int counter;
public:
    LabelManager() : counter(0) {}
    string new_label() { return "L" + std::to_string(counter++); }
    void reset() { counter = 0; }
};

// -------------------------------------------------------------------------
// Collects generated three address code instructions (as plain strings,
// already fully formatted, e.g. "t0 = a + b" or "L0:" or "// comment")
// and writes them to code.txt with the required header/footer.
// -------------------------------------------------------------------------
class CodeEmitter {
    vector<string> lines;
public:
    void emit(const string& instruction) {
        lines.push_back(instruction);
    }
    void emit_blank() {
        lines.push_back("");
    }
    void emit_comment(const string& comment) {
        lines.push_back("// " + comment);
    }
    void emit_label(const string& label) {
        lines.push_back(label + ":");
    }

    void write_to_file(const string& path) const {
        FILE* fp = fopen(path.c_str(), "w");
        if (!fp) return;
        fprintf(fp, "//========== THREE ADDRESS CODE ==========\n\n");
        fprintf(fp, "// This code was generated by a two-pass compiler\n");
        fprintf(fp, "// Format: \n");
        fprintf(fp, "// - t0, t1, etc. are temporary variables\n");
        fprintf(fp, "// - L0, L1, etc. are labels for jumps\n");
        fprintf(fp, "// - Operations follow the three-address code format\n\n");
        fprintf(fp, "// Three Address Code\n\n");
        for (const auto& l : lines) {
            fprintf(fp, "%s\n", l.c_str());
        }
        fprintf(fp, "\n\n//========== END OF CODE ==========\n");
        fclose(fp);
    }
};

// Globals shared across all AST node generate_code() implementations.
extern TempVarManager g_temp_mgr;
extern LabelManager g_label_mgr;
extern CodeEmitter g_code;

#endif
